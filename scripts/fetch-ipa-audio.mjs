// 把音标页用的 IPA 录音从 Wikimedia Commons 拉到 public/phonetics/,跟站点一起发出去,
// 运行时不再每次去 upload.wikimedia.org 取。
//
// 文件清单就是 src/lib/phonetics.ts 里的 recording("...") —— 不在这里再抄一份。
// Commons 的存放路径按文件名 md5 分桶(/<h[0]>/<h[0..1]>/<file>),这里用 node 算,
// 所以清单里只要文件名。取的是 Commons 转码出来的 mp3:原始文件是 ogg,iOS Safari 放不了。
//
//   npm run fetch:ipa          # 缺的下下来
//   npm run fetch:ipa -- --force   # 全部重下
import { createHash } from "node:crypto";
import { mkdir, readFile, readdir, writeFile, stat } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SRC = path.join(ROOT, "src/lib/phonetics.ts");
const OUT = path.join(ROOT, "public/phonetics");
const UA = "reader.peiyong.ai asset fetcher (https://reader.peiyong.ai)";
const force = process.argv.includes("--force");

/** Commons 的分桶:md5(文件名) 的前 1 位 / 前 2 位 */
function commonsUrl(file) {
  const h = createHash("md5").update(`${file}.ogg`).digest("hex");
  const enc = encodeURIComponent(`${file}.ogg`);
  return `https://upload.wikimedia.org/wikipedia/commons/transcoded/${h[0]}/${h.slice(0, 2)}/${enc}/${enc}.mp3`;
}

async function get(url, as) {
  for (let attempt = 1; ; attempt++) {
    const res = await fetch(url, { headers: { "user-agent": UA } });
    if (res.ok) return as === "json" ? res.json() : Buffer.from(await res.arrayBuffer());
    // 批量取会吃到限流,等一下再试
    if ((res.status === 429 || res.status >= 500) && attempt < 4) {
      await new Promise((r) => setTimeout(r, attempt * 2000));
      continue;
    }
    throw new Error(`HTTP ${res.status} ${url}`);
  }
}

/** Commons 的署名信息(CC BY-SA 要求随副本一起给出) */
async function credit(file) {
  const api = new URL("https://commons.wikimedia.org/w/api.php");
  api.search = new URLSearchParams({
    action: "query",
    format: "json",
    prop: "imageinfo",
    iiprop: "extmetadata|user",
    titles: `File:${file}.ogg`,
  }).toString();
  const data = await get(api, "json");
  const info = Object.values(data.query?.pages ?? {})[0]?.imageinfo?.[0] ?? {};
  const plain = (k) =>
    (info.extmetadata?.[k]?.value ?? "")
      .replace(/<[^>]*>/g, " ")
      .replace(/\s+/g, " ")
      .trim();
  // 一半的文件没填 Artist(早年的录音),这时署上传者 —— 这些录音都是上传者自己录的
  return {
    author: plain("Artist") || (info.user ? `${info.user} (uploader)` : "see source page"),
    license: plain("LicenseShortName") || "see source page",
    page: `https://commons.wikimedia.org/wiki/File:${encodeURIComponent(`${file}.ogg`)}`,
  };
}

const source = await readFile(SRC, "utf8");
const files = [...new Set([...source.matchAll(/recording\("([^"]+)"\)/g)].map((m) => m[1]))].sort();
if (!files.length) throw new Error(`没在 ${SRC} 里找到 recording("...") 清单`);

await mkdir(OUT, { recursive: true });
const credits = [];
let fetched = 0;
for (const file of files) {
  const dest = path.join(OUT, `${file}.mp3`);
  const have = !force && (await stat(dest).catch(() => null));
  if (!have) {
    const mp3 = await get(commonsUrl(file));
    if (mp3.length < 2000) throw new Error(`${file}: 下下来只有 ${mp3.length} 字节,不像音频`);
    await writeFile(dest, mp3);
    fetched++;
    console.log(`↓ ${file}.mp3 (${(mp3.length / 1024).toFixed(1)} KB)`);
  }
  credits.push({ file, ...(await credit(file)) });
}

const lines = [
  "IPA 录音来源 / Credits for the IPA recordings in this folder",
  "",
  "每个文件都是 Wikimedia Commons 上同名 .ogg 的 mp3 转码版,未作改动。",
  "Each file is an unmodified mp3 transcode of the same-named .ogg on Wikimedia Commons.",
  "由 scripts/fetch-ipa-audio.mjs 生成,勿手改。/ Generated by scripts/fetch-ipa-audio.mjs — do not edit.",
  "",
];
for (const c of credits) {
  lines.push(`${c.file}.mp3`, `  author:  ${c.author}`, `  license: ${c.license}`, `  source:  ${c.page}`, "");
}
await writeFile(path.join(OUT, "CREDITS.txt"), lines.join("\n"));

const extra = (await readdir(OUT)).filter((f) => f.endsWith(".mp3") && !files.includes(f.replace(/\.mp3$/, "")));
if (extra.length) console.warn(`⚠️ public/phonetics/ 里有清单外的文件,可以删:${extra.join(", ")}`);
console.log(`✅ ${files.length} 个录音就绪(本次下载 ${fetched} 个),CREDITS.txt 已刷新`);
